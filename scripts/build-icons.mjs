// Builds src/poi-icons.ts from the Iconify sets in devDependencies.
// Fluent Emoji High Contrast (MIT, Microsoft) is the base; Game Icons
// (CC BY 3.0, game-icons.net) fills species Fluent lacks.
// Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const sets = {
  f: JSON.parse(readFileSync('node_modules/@iconify-json/fluent-emoji-high-contrast/icons.json', 'utf8')),
  g: JSON.parse(readFileSync('node_modules/@iconify-json/game-icons/icons.json', 'utf8')),
};

/** App icon name -> "set:icon". */
const ICONS = {
  // animals
  monkey: 'f:monkey', bird: 'f:bird', crane: 'g:heron', flamingo: 'f:flamingo', porcupine: 'g:porcupine',
  crocodile: 'f:crocodile', fox: 'f:fox', otter: 'f:otter', camel: 'f:two-hump-camel', dromedary: 'f:camel',
  hippo: 'f:hippopotamus', ibis: 'g:ibis', antelope: 'f:deer', llama: 'f:llama', turtle: 'f:turtle', zebra: 'f:zebra',
  cattle: 'f:ox', giraffe: 'f:giraffe', elephant: 'f:elephant', snake: 'f:snake', lizard: 'f:lizard', owl: 'f:owl',
  kangaroo: 'f:kangaroo', armadillo: 'g:armadillo', seal: 'f:seal', parrot: 'f:parrot', eagle: 'f:eagle',
  sheep: 'f:ewe', leopard: 'f:leopard', capybara: 'f:beaver',
  // food, botanic, services
  restaurant: 'f:fork-and-knife-with-plate', snack: 'f:cup-with-straw', cactus: 'f:cactus', herb: 'f:herb',
  palm: 'f:palm-tree', tree: 'f:deciduous-tree', ticket: 'f:admission-tickets', info: 'f:information',
  gift: 'f:wrapped-gift', camera: 'f:camera', apple: 'f:red-apple', hospital: 'f:hospital',
  firstaid: 'f:adhesive-bandage', defib: 'f:high-voltage', viewpoint: 'g:binoculars', toilet: 'f:toilet',
  taxi: 'f:taxi', car: 'f:automobile', wheelchair: 'f:manual-wheelchair', train: 'f:locomotive',
  show: 'f:graduation-cap', paw: 'f:paw-prints', splash: 'f:playground-slide',
};

const out = {};
for (const [name, ref] of Object.entries(ICONS)) {
  const [setKey, icon] = ref.split(':');
  const set = sets[setKey];
  const data = set.icons[icon];
  if (!data) throw new Error(`missing icon ${ref}`);
  const w = data.width ?? set.width ?? 16;
  const h = data.height ?? set.height ?? 16;
  out[name] = { viewBox: `0 0 ${w} ${h}`, body: data.body };
}

writeFileSync(
  'src/poi-icons.ts',
  `// Generated by scripts/build-icons.mjs — do not edit.
// Fluent Emoji High Contrast © Microsoft (MIT). Game Icons © game-icons.net contributors (CC BY 3.0).
export const POI_ICONS: Record<string, { viewBox: string; body: string }> = ${JSON.stringify(out, null, 1)};

export function poiIconSvg(name: string | undefined, size = 20): string {
  const icon = (name && POI_ICONS[name]) || POI_ICONS.paw;
  return \`<svg viewBox="\${icon.viewBox}" width="\${size}" height="\${size}" fill="currentColor" aria-hidden="true">\${icon.body}</svg>\`;
}
`,
);
console.log(Object.keys(out).length, 'icons ->', 'src/poi-icons.ts');
